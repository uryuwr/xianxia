// ---------------- 饕餮纹（以 cx 为中线左右对称）：双目、眉、卷角、鼻梁；y 为纹带中线 ----------------
function taotie(m, k, cx, y, s = 1, op = 0.62) {
  const P = (pts) => m(pts.map(([x, yy]) => [cx + x * s, y + yy * s]));
  const half = (sg) => {
    const f = (pts) => pts.map(([x, yy]) => [x * sg, yy]);
    return [
      { s: P(f([[-3, -4], [-7, -6], [-11, -4]])), w: 1.6 * k, op, taper: 0.3, seed: 300 + sg },
      { s: P(f([[-4, 1], [-9, 2], [-13, -1], [-12, -5], [-9, -4]])), w: 1.3 * k, op: op * 0.85, taper: 0.4, seed: 310 + sg },
      { s: P(f([[-14, 3], [-18, 0], [-17, -4], [-14, -3]])), w: 1.2 * k, op: op * 0.75, taper: 0.4, seed: 320 + sg },
      { dot: P(f([[-6, -1]]))[0], r: 1.5 * k * s, c: INK, op: op + 0.15 },
    ];
  };
  return [...half(1), ...half(-1), { s: P([[0, -6], [0, 4]]), w: 1.5 * k, op, taper: 0.2, seed: 330 }];
}
// 雷纹（回字小勾）：一排
function leiwen(m, k, xs, y, op = 0.45) {
  // 方折回旋（左右交替镜像），不用圆勾，免得像字母
  return xs.map((x, i) => {
    const sg = i % 2 ? -1 : 1, P = (q) => q.map(([a, b]) => [x + a * sg, y + b]);
    return { s: m(P([[-2.5, 3], [-2.5, -3], [2.5, -3], [2.5, 1.5], [-0.5, 1.5], [-0.5, -1]])), w: 1 * k, op, taper: 0.15, press: 1, rough: 0.05, seed: 340 + i };
  });
}

